"""Seed a dashboard with a synthetic mountain-road run, the scenario library and a baseline evaluation.

No CARLA server is needed: the run is generated from a parametric switchback
route near Thimphu so the dashboard, KPI logic and evidence export can be
exercised end to end. Clearly labelled as synthetic in the run notes.
"""

import argparse
import json
import math
import os
import random
import sys
import tempfile
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from bhutan_sim.evaluation import evaluate_perception  # noqa: E402
from bhutan_sim.library import generate_library, library_manifest  # noqa: E402
from bhutan_sim.quality import assess_run  # noqa: E402
from bhutan_sim.safety_rules import check_samples, classify_events  # noqa: E402
from bhutan_sim.taxonomy import Taxonomy  # noqa: E402
from bhutan_sim.telemetry import DashboardClient, Event, RunManifest, Sample, TelemetryLogger, load_run  # noqa: E402


def synthetic_run(run_dir, run_id, scenario, seed=1, duration_s=240.0, rate_hz=20.0, source="vehicle"):
    rng = random.Random(seed)
    lat0, lon0 = 27.4712, 89.6339          # Thimphu, roughly
    m_per_deg_lat = 111320.0
    m_per_deg_lon = m_per_deg_lat * math.cos(math.radians(lat0))
    manifest = RunManifest(run_id=run_id, source=source, vehicle_class="truck", route_id="BT-Thimphu-Dochula:demo",
                           scenario_id=scenario["id"], scenario_hash=scenario["content_hash"], started_at=time.time() - duration_s,
                           map_name="synthetic", odd_zone="Thimphu-Dochula demo corridor",
                           streams={"video": False, "gnss": True, "imu": True, "can": source == "vehicle", "events": True},
                           consent_ref="CONSENT-DEMO-0001" if source == "vehicle" else None,
                           notes="SYNTHETIC demo run generated by seed_demo.py; not real vehicle data")
    logger = TelemetryLogger(run_dir, manifest)
    x = y = 0.0
    heading = 0.0
    speed = 8.0
    grade = 4.0
    t0 = manifest.started_at
    dt = 1.0 / rate_hz
    samples = []
    raw_events = []
    n = int(duration_s * rate_hz)
    lead = None
    for i in range(n):
        t = t0 + i * dt
        phase = (i * dt) % 60.0
        # Switchbacks every 60 s: 40 s straight, 20 s hairpin at 18 deg/s.
        yaw_rate = math.radians(18.0) if phase > 40.0 else rng.gauss(0.0, 0.01)
        grade = 6.0 if (i * dt) < 120 else -8.0
        target = 6.0 if phase > 40.0 else (11.0 if grade > 0 else 13.5)
        accel_x = max(-4.0, min(1.5, (target - speed) * 0.6 + rng.gauss(0, 0.15)))
        if 150 < i * dt < 153:   # a hard brake for a stopped vehicle after a curve
            accel_x = -3.6
            lead = 12.0 - (i * dt - 150) * 3.0
        elif lead is not None and i * dt >= 153:
            lead = None
        speed = max(0.0, speed + accel_x * dt)
        heading = (heading + math.degrees(yaw_rate) * dt) % 360.0
        x += speed * dt * math.sin(math.radians(heading))
        y += speed * dt * math.cos(math.radians(heading))
        accel_y = speed * yaw_rate + rng.gauss(0, 0.1)
        sample = Sample(t=t, frame=i, lat=lat0 + y / m_per_deg_lat, lon=lon0 + x / m_per_deg_lon, alt=2400.0 + y * grade / 100.0,
                        speed_mps=speed, heading_deg=heading, accel_x=accel_x, accel_y=accel_y, accel_z=0.0, yaw_rate=yaw_rate,
                        throttle=max(0.0, min(1.0, accel_x / 1.5)), brake=max(0.0, min(1.0, -accel_x / 4.0)), steer=max(-1, min(1, yaw_rate / 0.5)),
                        grade_pct=grade, lead_distance_m=lead, lead_rel_speed_mps=(-speed if lead is not None else None), source=source, x=x, y=y)
        if rng.random() < 0.002:
            continue  # occasional dropped sample, still inside the quality gates
        logger.sample(sample)
        samples.append(sample.to_dict())
        # Bird's-eye ground truth: a lead vehicle sometimes, pedestrians on the shoulder near the hairpins.
        objects = []
        if lead is not None:
            objects.append({"id": 900, "cls": "vehicle", "x": round(lead, 2), "y": 0.0, "role": "stalled_vehicle"})
        if phase > 38.0:
            objects.append({"id": 901, "cls": "pedestrian", "x": round(25.0 - (phase - 38.0) * 1.5, 2), "y": 2.4, "role": "pedestrian"})
        if 60 < i * dt < 75:
            objects.append({"id": 902, "cls": "animal", "x": round(45.0 - (i * dt - 60) * 2.5, 2), "y": -0.5, "role": "livestock"})
        logger.ground_truth({"frame": i, "objects": objects})
        if i * dt == 150.0:
            ev = Event(t=t, frame=i, event_class="stopped_vehicle_ahead", severity="warning", lat=sample.lat, lon=sample.lon, description="stalled truck after blind curve")
            logger.event(ev)
            raw_events.append(ev.to_dict())
        if abs(phase - 45.0) < dt / 2:
            ev = Event(t=t, frame=i, event_class="vru_close_pass", severity="warning", lat=sample.lat, lon=sample.lon, description="pedestrian on shoulder inside hairpin")
            logger.event(ev)
            raw_events.append(ev.to_dict())
        if abs(i * dt - 70.0) < dt / 2:
            ev = Event(t=t, frame=i, event_class="obstacle_ahead", severity="warning", lat=sample.lat, lon=sample.lon, description="cattle on carriageway")
            logger.event(ev)
            raw_events.append(ev.to_dict())
    violations = check_samples(samples, "truck", scenario["params"]["speed_limit_kph"]) + classify_events(raw_events)
    for v in violations:
        logger.event(v)
    logger.close()
    events = raw_events + [v.to_dict() for v in violations]
    quality = assess_run(run_id, samples, events, manifest.streams, expected_rate_hz=rate_hz, privacy_status="not_required" if source == "sim" else "redacted")
    return quality.to_dict()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dashboard", default=os.environ.get("BHUTAN_DASHBOARD_URL", "http://127.0.0.1:8787"))
    parser.add_argument("--token", default=os.environ.get("BHUTAN_DASHBOARD_TOKEN", "dev-writer-token"))
    parser.add_argument("--tenant", default=os.environ.get("BHUTAN_TENANT", "default"))
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--keep", default=None, help="directory to keep generated run folders in (default: temp)")
    args = parser.parse_args()

    client = DashboardClient(args.dashboard, args.token, args.tenant)
    print("health:", client.health())
    taxonomy = Taxonomy.load()
    templates = generate_library(taxonomy)
    manifest = library_manifest(templates, taxonomy.version)
    print("scenarios import:", client.upload_scenarios(manifest))
    for template in templates[:23]:
        client._request("POST", "/api/scenarios/%s/review" % template.id, {"review_status": "reviewed", "notes": "seed demo"})

    base = args.keep or tempfile.mkdtemp(prefix="bhutan-demo-")
    picks = []
    for family in ("blind_mountain_curve", "steep_descent_braking", "valley_fog", "livestock_on_road"):
        picks.append(next(t for t in templates if t.family == family))
    for index in range(args.runs):
        template = picks[index % len(picks)].to_dict()
        run_id = "demo-run-%02d" % (index + 1)
        run_dir = os.path.join(base, run_id)
        source = "vehicle" if index % 3 != 2 else "sim"
        quality = synthetic_run(run_dir, run_id, template, seed=index + 1, source=source)
        with open(os.path.join(run_dir, "quality.json"), "w", encoding="utf-8") as handle:
            json.dump(quality, handle, indent=2)
        client.upload_run_dir(run_dir, quality)
        # Baseline "model": drop far objects and some pedestrians so the failure clusters are non-trivial.
        rng = random.Random(index)
        gt = [json.loads(l) for l in open(os.path.join(run_dir, "ground_truth.jsonl"), encoding="utf-8") if l.strip()]
        det = []
        for frame in gt:
            dets = []
            for o in frame["objects"]:
                keep = 0.95 if o["x"] < 20 else 0.6 if o["x"] < 40 else 0.25
                if o["cls"] == "animal":
                    keep *= 0.5
                if rng.random() < keep:
                    dets.append({"cls": o["cls"], "x": o["x"] + rng.gauss(0, 0.4), "y": o["y"] + rng.gauss(0, 0.3), "score": round(rng.uniform(0.5, 0.99), 2)})
            det.append({"frame": frame["frame"], "detections": dets})
        report = evaluate_perception(gt, det, "baseline-bev", "0.1", run_id, scenario=template).to_dict()
        client.upload_evaluation(report)
        print("run %s (%s, %s): acceptance %.0f%%, %d events, evaluation recall %.2f" % (
            run_id, source, template["id"], quality["acceptance_rate"] * 100, len(load_run(run_dir)["events"]), report["overall"]["recall"]))
    client.register_clip({"clip_id": "demo-clip-01", "run_id": "demo-run-01", "t_start": 0, "t_end": 30, "content_type": "video/mp4", "consent_ref": "CONSENT-DEMO-0001", "redaction_status": "redacted"})
    client._request("POST", "/api/clips/demo-clip-01/governance", {"released": True})
    client.register_clip({"clip_id": "demo-clip-02", "run_id": "demo-run-02", "t_start": 0, "t_end": 30, "content_type": "video/mp4", "redaction_status": "pending"})
    client._request("POST", "/api/kpis/snapshot", {})
    print("done; run directories in", base)


if __name__ == "__main__":
    main()
