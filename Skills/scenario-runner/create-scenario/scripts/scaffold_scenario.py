#!/usr/bin/env python3
"""Scaffold and validate a new ScenarioRunner scenario.

    scaffold_scenario.py --name MyCutIn --town Town04 [--template T] [--out DIR]
    scaffold_scenario.py --list-templates
    scaffold_scenario.py validate --name MyCutIn [--out DIR]

Writes two files whose names ScenarioRunner requires to line up:
    <out>/srunner/scenarios/<snake_case>.py   class <Name>(BasicScenario)
    <out>/srunner/examples/<Name>.xml         <scenario type="<Name>" ...>
`validate` re-checks that alignment plus everything else that can stop a scenario
loading, without needing a simulator.
"""
from __future__ import annotations

import argparse
import ast
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

TEMPLATES = {
    "minimal": "one actor placed ahead, destroyed after the ego arrives",
    "follow_leading_vehicle": "a leader that drives then stops in the ego's lane",
    "cut_in": "an actor in the adjacent lane that cuts in when the ego closes",
    "pedestrian": "a walker that crosses in front of the ego when triggered",
}

BODY = '''#!/usr/bin/env python
#
# This work is licensed under the terms of the MIT license.
# For a copy, see <https://opensource.org/licenses/MIT>.

"""
{name}

{blurb}

Generated by the create-scenario skill. Run with:
    python3 scenario_runner.py --scenario {name}_1 --reloadWorld
"""

import py_trees
import carla

from srunner.scenariomanager.carla_data_provider import CarlaDataProvider
from srunner.scenariomanager.scenarioatomics.atomic_behaviors import (
    ActorDestroy,
    ActorTransformSetter,
    Idle,
    KeepVelocity,
    StopVehicle,
    WaypointFollower,
)
from srunner.scenariomanager.scenarioatomics.atomic_criteria import CollisionTest
from srunner.scenariomanager.scenarioatomics.atomic_trigger_conditions import (
    DriveDistance,
    InTriggerDistanceToVehicle,
)
from srunner.scenarios.basic_scenario import BasicScenario
from srunner.tools.scenario_helper import get_waypoint_in_distance


class {name}(BasicScenario):

    """
    {blurb}

    The scenario is parameterised from its XML config through
    config.other_parameters; every value there is a *string*, so cast it.
    """

    def __init__(self, world, ego_vehicles, config, randomize=False,
                 debug_mode=False, criteria_enable=True, timeout={timeout}):
        # self.timeout must be set BEFORE super().__init__: the base class reads
        # it while assembling the tree.
        self.timeout = timeout
        self._world = world
        self._map = CarlaDataProvider.get_map()
        self._reference_waypoint = self._map.get_waypoint(config.trigger_points[0].location)

        # --- parameters from the XML config ---
        self._distance = 40.0
        if "distance" in config.other_parameters:
            self._distance = float(config.other_parameters["distance"]["value"])
        self._speed = 10.0
        if "speed" in config.other_parameters:
            self._speed = float(config.other_parameters["speed"]["value"])

        super({name}, self).__init__("{name}", ego_vehicles, config, world,
                                     debug_mode, criteria_enable=criteria_enable)

    def _initialize_actors(self, config):
        """Spawn the scenario's actors.

        Always go through CarlaDataProvider.request_new_actor — a direct
        world.spawn_actor is not registered with the provider, so the atomics
        cannot read its velocity and it is never cleaned up. Everything appended
        to self.other_actors is destroyed for you.
        """
{init_body}

    def _create_behavior(self):
        """The behaviour tree. It MUST be able to terminate, or the run hangs
        until self.timeout — that is what an apparently stuck scenario is."""
{behavior_body}

    def _create_test_criteria(self):
        """Criteria decide pass/fail and raise the TrafficEvents the Leaderboard
        turns into infractions."""
        return [CollisionTest(self.ego_vehicles[0])]

    def __del__(self):
        self.remove_all_actors()
'''

INIT = {
    "minimal": '''        waypoint, _ = get_waypoint_in_distance(self._reference_waypoint, self._distance)
        transform = carla.Transform(
            waypoint.transform.location + carla.Location(z=0.5),
            waypoint.transform.rotation)
        actor = CarlaDataProvider.request_new_actor("vehicle.tesla.model3", transform)
        if actor is None:
            raise RuntimeError("could not spawn the scenario actor — the spawn point is blocked")
        self.other_actors.append(actor)''',
    "follow_leading_vehicle": '''        waypoint, _ = get_waypoint_in_distance(self._reference_waypoint, self._distance)
        transform = carla.Transform(
            waypoint.transform.location + carla.Location(z=0.5),
            waypoint.transform.rotation)
        leader = CarlaDataProvider.request_new_actor("vehicle.nissan.patrol", transform)
        if leader is None:
            raise RuntimeError("could not spawn the leading vehicle")
        self.other_actors.append(leader)
        self._leader_transform = transform''',
    "cut_in": '''        waypoint, _ = get_waypoint_in_distance(self._reference_waypoint, self._distance)
        side = waypoint.get_left_lane() or waypoint.get_right_lane()
        if side is None:
            raise RuntimeError("no adjacent lane at the trigger point — pick another town/position")
        transform = carla.Transform(
            side.transform.location + carla.Location(z=0.5), side.transform.rotation)
        actor = CarlaDataProvider.request_new_actor("vehicle.audi.tt", transform)
        if actor is None:
            raise RuntimeError("could not spawn the cut-in vehicle")
        self.other_actors.append(actor)''',
    "pedestrian": '''        waypoint, _ = get_waypoint_in_distance(self._reference_waypoint, self._distance)
        # Offset sideways so the walker starts at the kerb, not in the lane.
        right = waypoint.transform.get_right_vector()
        location = waypoint.transform.location + carla.Location(
            x=4.0 * right.x, y=4.0 * right.y, z=1.0)
        transform = carla.Transform(location, waypoint.transform.rotation)
        walker = CarlaDataProvider.request_new_actor("walker.pedestrian.0001", transform)
        if walker is None:
            raise RuntimeError("could not spawn the walker")
        self.other_actors.append(walker)''',
}

BEHAVIOR = {
    "minimal": '''        root = py_trees.composites.Sequence("{name}")
        root.add_child(InTriggerDistanceToVehicle(
            self.other_actors[0], self.ego_vehicles[0], 20))
        root.add_child(Idle(3))
        root.add_child(ActorDestroy(self.other_actors[0]))
        return root''',
    "follow_leading_vehicle": '''        # Drive the leader, then stop it, then wait for the ego to close in.
        root = py_trees.composites.Sequence("{name}")
        root.add_child(ActorTransformSetter(self.other_actors[0], self._leader_transform))

        drive = py_trees.composites.Parallel(
            "leader drives until the ego is near",
            policy=py_trees.common.ParallelPolicy.SUCCESS_ON_ONE)
        drive.add_child(WaypointFollower(self.other_actors[0], self._speed))
        drive.add_child(InTriggerDistanceToVehicle(
            self.other_actors[0], self.ego_vehicles[0], 25))
        root.add_child(drive)

        root.add_child(StopVehicle(self.other_actors[0], 1.0))
        root.add_child(DriveDistance(self.ego_vehicles[0], 20))
        root.add_child(ActorDestroy(self.other_actors[0]))
        return root''',
    "cut_in": '''        root = py_trees.composites.Sequence("{name}")
        root.add_child(InTriggerDistanceToVehicle(
            self.other_actors[0], self.ego_vehicles[0], 30))

        # LaneChange returns SUCCESS once distance_other_lane is covered.
        from srunner.scenariomanager.scenarioatomics.atomic_behaviors import LaneChange
        root.add_child(LaneChange(self.other_actors[0], speed=self._speed,
                                 distance_other_lane=30))
        root.add_child(DriveDistance(self.ego_vehicles[0], 30))
        root.add_child(ActorDestroy(self.other_actors[0]))
        return root''',
    "pedestrian": '''        root = py_trees.composites.Sequence("{name}")
        root.add_child(InTriggerDistanceToVehicle(
            self.other_actors[0], self.ego_vehicles[0], 25))

        cross = py_trees.composites.Parallel(
            "walker crosses",
            policy=py_trees.common.ParallelPolicy.SUCCESS_ON_ONE)
        cross.add_child(KeepVelocity(self.other_actors[0], 1.5))
        cross.add_child(DriveDistance(self.other_actors[0], 8))
        root.add_child(cross)

        root.add_child(DriveDistance(self.ego_vehicles[0], 20))
        root.add_child(ActorDestroy(self.other_actors[0]))
        return root''',
}

XML = '''<?xml version="1.0"?>
<!-- Generated by the create-scenario skill.
     type= must match the class name exactly, or ScenarioRunner reports
     "Scenario '{name}_1' not supported". Duplicate the <scenario> element with a
     new name to get {name}_2, {name}_3 ... and run them all with group:{name}. -->
<scenarios>
    <scenario name="{name}_1" type="{name}" town="{town}">
        <ego_vehicle x="{x}" y="{y}" z="{z}" yaw="{yaw}" model="{ego}" rolename="hero"/>
        <distance value="40"/>
        <speed value="10"/>
    </scenario>
</scenarios>
'''

# Sensible ego spawn points per town, so the scaffold runs before being edited.
SPAWNS = {
    "Town01": (338.7, 226.7, 0.5, 270),
    "Town02": (132.0, 215.0, 0.5, 90),
    "Town03": (207.0, 59.0, 0.5, 180),
    "Town04": (-25.0, -240.0, 0.5, 0),
    "Town05": (-145.5, -1.0, 0.5, 180),
    "Town06": (-100.0, 50.0, 0.5, 0),
    "Town10HD_Opt": (0.7, 28.1, 0.5, 0),
}


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def sr_root(explicit: str | None) -> Path:
    for c in [explicit, os.environ.get("SCENARIO_RUNNER_ROOT"), os.getcwd(),
              str(Path.home() / "scenario_runner")]:
        if c and (Path(c) / "srunner" / "scenarios").is_dir():
            return Path(c).resolve()
    sys.exit("no scenario_runner checkout found — export SCENARIO_RUNNER_ROOT")


def branch(root: Path) -> str:
    """Which SR flavour this checkout is.

    The branch name is the fast path, but it is "HEAD" in a detached checkout, a
    worktree, a tarball or a docker image — so fall back to a content probe.
    `srunner/scenic/` exists only on ue5-master, and change_lane.py exists on
    every branch except ue5-master.
    """
    import subprocess

    name = subprocess.run(["git", "-C", str(root), "rev-parse", "--abbrev-ref", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    if name and name != "HEAD":
        return name
    if (root / "srunner" / "scenic").is_dir() and not (root / "srunner" / "scenarios" / "change_lane.py").is_file():
        return "ue5-master"
    return name or "unknown"


def do_scaffold(args) -> None:
    name = args.name
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name):
        sys.exit(f"--name {name!r} must be TitleCase with no underscores "
                 "(the class name and the XML type must match)")
    sr = sr_root(args.root)
    out = Path(args.out).resolve() if args.out else sr
    py_dir, xml_dir = out / "srunner" / "scenarios", out / "srunner" / "examples"
    py_dir.mkdir(parents=True, exist_ok=True)
    xml_dir.mkdir(parents=True, exist_ok=True)
    py_path, xml_path = py_dir / f"{snake(name)}.py", xml_dir / f"{name}.xml"
    for p in (py_path, xml_path):
        if p.exists() and not args.force:
            sys.exit(f"{p} exists — pass --force to overwrite")

    br = branch(sr)
    town = args.town
    if br == "ue5-master" and town != "Town10HD_Opt":
        print(f"WARNING branch is ue5-master: CARLA 0.10.0 only ships Town10HD_Opt, "
              f"so town={town} will not load. Use --town Town10HD_Opt.")
    ego = "vehicle.lincoln.mkz" if br == "ue5-master" else "vehicle.lincoln.mkz_2017"
    x, y, z, yaw = SPAWNS.get(town, (0.0, 0.0, 0.5, 0))

    py_path.write_text(BODY.format(
        name=name,
        blurb=TEMPLATES[args.template],
        timeout=args.timeout,
        init_body=INIT[args.template],
        behavior_body=BEHAVIOR[args.template].format(name=name),
    ))
    xml_path.write_text(XML.format(name=name, town=town, x=x, y=y, z=z, yaw=yaw, ego=ego))
    print(f"wrote {py_path}")
    print(f"wrote {xml_path}")
    print(f"\ntemplate : {args.template} — {TEMPLATES[args.template]}")
    print(f"validate : python3 {sys.argv[0]} validate --name {name}"
          + (f" --out {out}" if args.out else ""))
    if args.out:
        print(f"run      : python3 {sr}/scenario_runner.py --scenario {name}_1 --reloadWorld \\")
        print(f"             --additionalScenario {py_path} --configFile {xml_path}")
    else:
        print(f"run      : DEBUG=1 OUTPUT=1 bash ../run-scenario/scripts/run_scenario.sh {name}_1")


def do_validate(args) -> None:
    name = args.name
    sr = sr_root(args.root)
    out = Path(args.out).resolve() if args.out else sr
    py_path = out / "srunner" / "scenarios" / f"{snake(name)}.py"
    xml_path = out / "srunner" / "examples" / f"{name}.xml"
    rc = 0

    def ok(m): print(f"PASS  {m}")

    def bad(m):
        nonlocal rc
        print(f"FAIL  {m}")
        rc = 1

    def warn(m): print(f"WARN  {m}")

    if not py_path.is_file():
        bad(f"{py_path} missing")
        sys.exit(rc)
    ok(f"module {py_path}")

    # Parse rather than import: importing needs carla + a live CarlaDataProvider,
    # and every mistake worth catching here is visible in the AST.
    try:
        tree = ast.parse(py_path.read_text())
    except SyntaxError as e:
        bad(f"syntax error at line {e.lineno}: {e.msg}")
        sys.exit(rc)
    ok("module parses")

    cls = next((n for n in ast.walk(tree)
                if isinstance(n, ast.ClassDef) and n.name == name), None)
    if cls is None:
        found = [n.name for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
        bad(f"no `class {name}` in the module (found: {', '.join(found) or 'none'})")
    else:
        ok(f"class {name} defined")
        bases = [b.id if isinstance(b, ast.Name) else getattr(b, "attr", "?") for b in cls.bases]
        if "BasicScenario" not in bases:
            bad(f"class {name} derives from {bases}, not BasicScenario")
        else:
            ok("derives from BasicScenario")
        methods = {n.name for n in cls.body if isinstance(n, ast.FunctionDef)}
        for m in ("__init__", "_initialize_actors", "_create_behavior", "_create_test_criteria"):
            (ok if m in methods else bad)(f"method {m}" + ("" if m in methods else " missing"))
        beh = next((n for n in cls.body if isinstance(n, ast.FunctionDef)
                    and n.name == "_create_behavior"), None)
        if beh and not any(isinstance(n, ast.Return) and n.value is not None for n in ast.walk(beh)):
            bad("_create_behavior never returns a value — the scenario cannot build a tree")
        elif beh:
            ok("_create_behavior returns a tree")
        # A direct world.spawn_actor bypasses the provider: the atomics then fail
        # with "not found" and the actor leaks between runs. Look for the *call*
        # in the AST, not the string — the text appears in docstrings that warn
        # against it, which would make this a permanent false positive.
        calls = [n for n in ast.walk(cls)
                 if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
                 and n.func.attr in ("spawn_actor", "try_spawn_actor")]
        if calls:
            warn(f"world.spawn_actor called at line {calls[0].lineno} — use "
                 "CarlaDataProvider.request_new_actor instead")
        appends = [n for n in ast.walk(cls)
                   if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
                   and n.func.attr == "append"
                   and "other_actors" in ast.dump(n.func.value)]
        if not appends and "_initialize_actors" in methods:
            warn("nothing appended to self.other_actors — spawned actors will not be destroyed")

    if not xml_path.is_file():
        bad(f"{xml_path} missing")
        sys.exit(rc)
    try:
        root = ET.parse(xml_path).getroot()
    except ET.ParseError as e:
        bad(f"{xml_path.name} is not valid XML: {e}")
        sys.exit(rc)
    ok(f"config {xml_path}")
    scs = root.findall("scenario")
    if not scs:
        bad("no <scenario> elements in the config")
    for s in scs:
        t, n, town = s.attrib.get("type"), s.attrib.get("name"), s.attrib.get("town")
        (ok if t == name else bad)(
            f"{n}: type={t!r}" + ("" if t == name else f" does not match the class name {name!r}"))
        if not s.findall("ego_vehicle"):
            bad(f"{n}: no <ego_vehicle> — ScenarioRunner has nothing to spawn")
        br = branch(sr)
        valid = {"Town10HD_Opt"} if br == "ue5-master" else {
            "Town01", "Town02", "Town03", "Town04", "Town05", "Town06", "Town07",
            "Town10HD", "Town10HD_Opt", "Town11", "Town12", "Town13", "Town15"}
        (ok if town in valid else bad)(
            f"{n}: town={town!r}" + ("" if town in valid else f" is not available on branch {br}"))
        params = [c.tag for c in s if c.tag != "ego_vehicle"]
        if params:
            ok(f"{n}: parameters {', '.join(params)} (read via config.other_parameters, all strings)")

    if args.out:
        print("\nNOTE this scenario is outside the checkout: run it with "
              "--additionalScenario and --configFile,")
        print("     since ScenarioRunner only globs $SCENARIO_RUNNER_ROOT/srunner/scenarios/*.py")
    print("\nvalidation " + ("OK" if rc == 0 else "FAILED"))
    sys.exit(rc)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mode", nargs="?", default="scaffold", choices=["scaffold", "validate"])
    ap.add_argument("--name", help="TitleCase scenario/class name, e.g. MyCutIn")
    ap.add_argument("--town", default="Town04")
    ap.add_argument("--template", default="minimal", choices=sorted(TEMPLATES))
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--out", help="write outside the checkout (needs --additionalScenario to run)")
    ap.add_argument("--root", help="scenario_runner checkout")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--list-templates", action="store_true")
    args = ap.parse_args()

    if args.list_templates:
        for k, v in TEMPLATES.items():
            print(f"{k:24} {v}")
        return
    if not args.name:
        ap.error("--name is required")
    (do_validate if args.mode == "validate" else do_scaffold)(args)


if __name__ == "__main__":
    main()
