MAP_SENSOR = "            {'type': 'sensor.opendrive_map', 'id': 'OpenDRIVE',\n" \
             "              'reading_frequency': 1},   # MAP tracks only; returns the whole .xodr\n"


def do_scaffold(args) -> None:
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", args.name):
        sys.exit(f"--name {args.name!r} must be TitleCase with no underscores")
    lb = find("lb")
    version = lb_version(lb) if lb else "2.1"
    if lb is None:
        print("WARNING no leaderboard checkout found; assuming 2.x constructor signature")
    out_dir = Path(args.out).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{snake(args.name)}.py"
    if path.exists() and not args.force:
        sys.exit(f"{path} exists — pass --force to overwrite")
    ctor = (CTOR_1 if version == "1.0" else CTOR_2).format(name=args.name)
    if version == "1.0" and args.track.endswith("QUALIFIER"):
        sys.exit(f"track {args.track} does not exist in leaderboard 1.0 (only SENSORS and MAP)")
    path.write_text(TEMPLATE.format(
        name=args.name, file=path.name, track=args.track, track_enum=args.track,
        version=version, out=path, ctor=ctor,
        map_sensor=MAP_SENSOR if args.track.startswith("MAP") else "",
    ))
    print(f"wrote {path}   (leaderboard {version}, track {args.track})")
    print(f"\nvalidate : python3 {sys.argv[0]} validate --agent {path} --track {args.track}")
    print(f"run      : TEAM_AGENT={path} bash ../run-leaderboard-evaluation/scripts/run_leaderboard.sh --routes-subset 0")


def load_sensors(agent_path: Path) -> tuple[list[dict], str | None]:
    """Get sensors() and self.track without a simulator.

    Importing the module is the honest way, but agents import torch, ROS and other
    heavy things. Try a real import first, then fall back to evaluating just the
    sensors() return expression from the AST.
    """
    name = agent_path.stem
    expect = name.title().replace("_", "")
    src = agent_path.read_text()
    tree = ast.parse(src)
    cls = next((n for n in ast.walk(tree) if isinstance(n, ast.ClassDef) and n.name == expect), None)
    if cls is None:
        found = [n.name for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
        sys.exit(f"FAIL  {agent_path.name} must define `class {expect}` "
                 f"(the evaluator derives it from the file name); found: {', '.join(found) or 'none'}")
    print(f"PASS  class {expect} found")

    track = None
    for n in ast.walk(cls):
        if isinstance(n, ast.Assign) and isinstance(n.value, ast.Attribute):
            for t in n.targets:
                if isinstance(t, ast.Attribute) and t.attr == "track":
                    track = n.value.attr
    fn = next((n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == "sensors"), None)
    if fn is None:
        sys.exit("FAIL  no sensors() method")

    # Try the import path first — it handles sensors() built with loops or config.
    try:
        spec = importlib.util.spec_from_file_location(name, agent_path)
        mod = importlib.util.module_from_spec(spec)
        sys.path.insert(0, str(agent_path.parent))
        spec.loader.exec_module(mod)
        cls_obj = getattr(mod, expect)
        inst = cls_obj.__new__(cls_obj)
        sensors = cls_obj.sensors(inst)
        print("PASS  sensors() evaluated by importing the module")
        return sensors, track
    except Exception as e:
        print(f"INFO  could not import the agent ({type(e).__name__}: {e})")
        print("INFO  falling back to a static read of the sensors() return value")

    for n in ast.walk(fn):
        if isinstance(n, ast.Return) and n.value is not None:
            try:
                return ast.literal_eval(n.value), track
            except ValueError:
                sys.exit("FAIL  sensors() does not return a literal list and the module "
                         "could not be imported — install its dependencies and retry")
    sys.exit("FAIL  sensors() returns nothing")


def limits_from_source(lb: Path, track: str) -> tuple[dict, float, list[str]]:
    """Read the budget tables straight out of agent_wrapper.py.

    Importing the validator is preferable, but agent_wrapper imports
    ros_base_agent, which imports transforms3d unconditionally — so validating a
    plain non-ROS agent needs the ROS dependency installed. When it is not, parse
    the module instead: the tables are literal dicts at module scope.
    """
    src = (lb / "leaderboard" / "autoagents" / "agent_wrapper.py").read_text()
    tree = ast.parse(src)
    tables: dict[str, dict] = {}
    radius = 3.0
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        name = node.targets[0].id if isinstance(node.targets[0], ast.Name) else None
        if name in ("SENSORS_LIMITS", "QUALIFIER_SENSORS_LIMITS"):
            try:
                tables[name] = ast.literal_eval(node.value)
            except ValueError:
                pass
        elif name == "MAX_ALLOWED_RADIUS_SENSOR":
            radius = float(ast.literal_eval(node.value))
    aa = (lb / "leaderboard" / "autoagents" / "autonomous_agent.py").read_text()
    tracks = re.findall(r"^\s+(\w+)\s*=\s*'\1'", aa, re.M)
    table = tables.get("QUALIFIER_SENSORS_LIMITS" if track.endswith("QUALIFIER") else "SENSORS_LIMITS",
                       tables.get("SENSORS_LIMITS", {}))
    return table, radius, tracks


def validate_from_source(sensors: list[dict], track: str, lb: Path) -> int:
    """Reimplementation of validate_sensor_configuration over parsed limits.

    Mirrors leaderboard/autoagents/agent_wrapper.validate_sensor_configuration:
    unique ids, allowed types, opendrive_map only off the SENSORS tracks, mount
    radius, per-type counts.
    """
    import math
    from collections import Counter

    table, radius, tracks = limits_from_source(lb, track)
    if not table:
        print("FAIL  could not read the sensor limits out of agent_wrapper.py")
        return 1
    if track not in tracks:
        print(f"FAIL  track {track!r} does not exist in this leaderboard "
              f"(available: {', '.join(tracks)})")
        return 1
    rc, ids = 0, []
    for s in sensors:
        sid = s.get("id")
        if sid in ids:
            print(f"FAIL  Duplicated sensor tag [{sid}]")
            rc = 1
        ids.append(sid)
        if s.get("type") not in table:
            print(f"FAIL  Illegal sensor '{s.get('type')}' used for Track [{track}]")
            rc = 1
        if track == "SENSORS" and str(s.get("type", "")).startswith("sensor.opendrive_map"):
            print(f"FAIL  Illegal sensor 'sensor.opendrive_map' used for Track [{track}]")
            rc = 1
        if all(k in s for k in ("x", "y", "z")):
            r = math.sqrt(s["x"] ** 2 + s["y"] ** 2 + s["z"] ** 2)
            if r > radius:
                print(f"FAIL  Illegal sensor extrinsics for '{sid}': radius {r:.2f} m > {radius} m")
                rc = 1
    counts = Counter(s.get("type") for s in sensors)
    for t, limit in table.items():
        if counts.get(t, 0) > limit:
            print(f"FAIL  Too many {t} used! Maximum allowed is {limit}, "
                  f"but {counts[t]} were requested.")
            rc = 1
    if rc == 0:
        print(f"PASS  sensor configuration is valid for track {track} "
              "(checked against the parsed limits, not the imported validator)")
    return rc


def do_validate(args) -> None:
    lb, sr = find("lb"), find("sr")
    if lb is None:
        sys.exit("no leaderboard checkout found — export LEADERBOARD_ROOT")
    agent = Path(args.agent).expanduser().resolve()
    if not agent.is_file():
        sys.exit(f"{agent} not found")
    version = lb_version(lb)
    print(f"leaderboard {version} at {lb}")

    sensors, declared_track = load_sensors(agent)
    print(f"PASS  {len(sensors)} sensor(s) declared")
    if declared_track:
        print(f"INFO  self.track = Track.{declared_track}")
        if declared_track != args.track:
            print(f"WARN  agent sets Track.{declared_track} but validating against {args.track};"
                  " the evaluator rejects a mismatch with --track")

    # Use the checkout's own validator: the budgets live there and differ by version.
    sys.path.insert(0, str(lb))
    if sr:
        sys.path.insert(0, str(sr))
    imported = True
    try:
        from leaderboard.autoagents.agent_wrapper import validate_sensor_configuration
        from leaderboard.autoagents.autonomous_agent import Track
        from leaderboard.envs.sensor_interface import SensorConfigurationInvalid
    except Exception as e:
        # agent_wrapper -> ros_base_agent -> transforms3d, so a non-ROS agent still
        # needs the ROS dependency for the real validator. Fall back rather than
        # refusing to check anything.
        print(f"INFO  cannot import the leaderboard validator ({type(e).__name__}: {e})")
        print("INFO  checking against the limits parsed from agent_wrapper.py instead")
        print("INFO    (for the real validator: pip install -r $LEADERBOARD_ROOT/requirements.txt"
              " -r $SCENARIO_RUNNER_ROOT/requirements.txt)")
        imported = False

    if imported:
        try:
            track = Track(args.track)
        except ValueError:
            sys.exit(f"FAIL  track {args.track!r} does not exist in leaderboard {version} "
                     f"(available: {', '.join(t.value for t in Track)})")
        try:
            validate_sensor_configuration(sensors, track, args.track)
            print(f"PASS  sensor configuration is valid for track {args.track}")
        except SensorConfigurationInvalid as e:
            print(f"FAIL  {e}")
            sys.exit(1)
    elif validate_from_source(sensors, args.track, lb) != 0:
        sys.exit(1)

    # Advisory checks the validator does not make.
    from collections import Counter
    import math

    counts = Counter(s["type"] for s in sensors)
    for t, n in sorted(counts.items()):
        print(f"      {t:26} {n}")
    for s in sensors:
        if all(k in s for k in ("x", "y", "z")):
            r = math.sqrt(s["x"] ** 2 + s["y"] ** 2 + s["z"] ** 2)
            if r > 2.5:
                print(f"WARN  {s['id']}: mount radius {r:.2f} m is close to the 3.0 m limit")
    for s in sensors:
        if s["type"] == "sensor.lidar.ray_cast" and any(
                k in s for k in ("range", "channels", "points_per_second", "rotation_frequency")):
            print(f"WARN  {s['id']}: lidar attributes are IGNORED — agent_wrapper fixes them "
                  "(64 ch, 85 m, 10 Hz, 600k pts/s)")
        if s["type"] == "sensor.camera.rgb" and not all(k in s for k in ("width", "height", "fov")):
            print(f"WARN  {s['id']}: camera without width/height/fov — KeyError at setup time")
    if "sensor.speedometer" not in counts:
        print("WARN  no speedometer: there is no other way to know your own speed on the SENSORS track")
    print("\nvalidation OK")


def do_budget(args) -> None:
    lb = find("lb")
    if lb is None:
        sys.exit("no leaderboard checkout found — export LEADERBOARD_ROOT")
    # Parsed, not imported: agent_wrapper pulls in transforms3d via ros_base_agent,
    # and the budget should be printable in a bare environment.
    main, radius, tracks = limits_from_source(lb, "SENSORS")
    qual, _, _ = limits_from_source(lb, "SENSORS_QUALIFIER")
    print(f"leaderboard {lb_version(lb)}   MAX_ALLOWED_RADIUS_SENSOR = {radius} m")
    print(f"tracks: {', '.join(tracks)}")
    print("\nmain tracks (SENSORS, MAP):")
    for k, v in main.items():
        print(f"  {k:26} {v}")
    if qual != main:
        print("\nqualifier tracks:")
        for k, v in qual.items():
            print(f"  {k:26} {v}")
    print("\nsensor.opendrive_map is rejected on the SENSORS tracks (that is the MAP difference)")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("scaffold")
    p.add_argument("--name", required=True)
    p.add_argument("--track", default="SENSORS", choices=TRACKS)
    p.add_argument("--out", default=str(Path.home() / "team_code"))
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=do_scaffold)
    p = sub.add_parser("validate")
    p.add_argument("--agent", required=True)
    p.add_argument("--track", default=os.environ.get("CHALLENGE_TRACK_CODENAME", "SENSORS"))
    p.set_defaults(func=do_validate)
    p = sub.add_parser("budget")
    p.add_argument("--track", default="SENSORS")
    p.set_defaults(func=do_budget)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
